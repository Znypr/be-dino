"""BD-1217: generate src/shared/LowPolyClips.luau from tools/blender/dino_clips.py (the same keys author the Blender actions).

    python tools/blender/gen_dino_clips_luau.py           # write the module
    python tools/blender/gen_dino_clips_luau.py --check   # exit 1 when the module is out of date or a key breaks the calm limits
Plain Python, no Blender needed.
"""
import argparse
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
DEST = ROOT / "src" / "shared" / "LowPolyClips.luau"


def load():
    ns = {}
    exec((HERE / "dino_clips.py").read_text(encoding="utf8"), ns)
    return ns


def problems(ns):
    out = []
    for name, clip in ns["CLIPS"].items():
        length = clip["length"]
        for role, track in clip["tracks"].items():
            if role not in ns["ROLES"]:
                out.append("%s: unknown role %s" % (name, role))
            for channel, keys in track.items():
                if channel not in ns["CHANNELS"]:
                    out.append("%s.%s: unknown channel %s" % (name, role, channel))
                times = [k[0] for k in keys]
                if times != sorted(times) or len(set(times)) != len(times):
                    out.append("%s.%s.%s: key times not increasing" % (name, role, channel))
                if keys[0] != (0, 0) or keys[-1][1] != 0 or abs(keys[-1][0] - length) > 1e-9:
                    out.append("%s.%s.%s: must start at (0, 0) and end at 0 at the clip length" % (name, role, channel))
                limit = {"bob": ns["MAX_BOB"], "fwd": ns["MAX_FWD"]}.get(channel, ns["MAX_DEG"])
                for t, v in keys:
                    if abs(v) > limit + 1e-9:
                        out.append("%s.%s.%s: %s at %ss is over the calm limit %s" % (name, role, channel, v, t, limit))
                if channel == "bob" and any(v < 0 for _, v in keys):
                    out.append("%s.root.bob: below 0 sinks the feet into the ground" % name)
                if channel == "bob" and role != "root" or channel == "fwd" and role != "head":
                    out.append("%s.%s: %s belongs on the %s track" % (name, role, channel, "root" if channel == "bob" else "head"))
    return out


def f(x):
    s = ("%.4f" % x).rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def render(ns):
    lines = ['''--!strict
-- BD-1217: authored clips for the V3 low-poly dinos (eat, happy, look-around). GENERATED by tools/blender/gen_dino_clips_luau.py from
-- tools/blender/dino_clips.py (the same keys author the Blender actions in assets/blender/anim/DinoClips.blend). Do not edit by hand.
-- One track per body ROLE (LowPolyPose.Roles), so a clip fits every species. Pure (no Roblox types): tools/verify_lowpoly_clips.py runs it.
-- LowPolyAnimator adds sample() on top of the procedural pose. Angles come out in radians; bob and fwd are fractions of the dino height.
local Clips = {}
Clips.NeckShare = %s
-- roles whose roll follows the part's side (a positive roll opens a wing on both sides)
Clips.SideRoll = {wing = true, flipper = true, arm = true}
Clips.Data = {''' % f(ns["NECK_SHARE"])]
    for name, clip in ns["CLIPS"].items():
        lines.append("\t%s = {length = %s, tracks = {" % (name, f(clip["length"])))
        for role in ns["ROLES"]:
            track = clip["tracks"].get(role)
            if not track:
                continue
            parts = []
            for channel in ns["CHANNELS"]:
                if channel in track:
                    parts.append("%s = {%s}" % (channel, ", ".join("{%s, %s}" % (f(t), f(v)) for t, v in track[channel])))
            lines.append("\t\t%s = {%s}," % (role, ", ".join(parts)))
        lines.append("\t}},")
    lines.append("}")
    lines.append('''
-- value of one channel at time t (keys {{t, v}, ...} sorted, first and last value 0): cubic Hermite, monotone-clamped tangents (no overshoot)
local function hermite(keys: {{number}}, t: number): number
\tlocal n = #keys
\tif n == 0 or t <= keys[1][1] or t >= keys[n][1] then return 0 end
\tlocal i = 1
\twhile i < n - 1 and keys[i + 1][1] <= t do i += 1 end
\tlocal function slope(j: number): number
\t\tif j <= 1 or j >= n then return 0 end
\t\tlocal ta, va, tb, vb, tc, vc = keys[j - 1][1], keys[j - 1][2], keys[j][1], keys[j][2], keys[j + 1][1], keys[j + 1][2]
\t\tif (vb - va) * (vc - vb) <= 0 then return 0 end -- local extremum: flat tangent
\t\t-- monotone clamp (Fritsch-Carlson): never steeper than 3x the gentler neighbouring secant, so no segment overshoots its keys
\t\tlocal cap = 3 * math.min(math.abs((vb - va) / (tb - ta)), math.abs((vc - vb) / (tc - tb)))
\t\treturn math.clamp((vc - va) / (tc - ta), -cap, cap)
\tend
\tlocal t0, v0, t1, v1 = keys[i][1], keys[i][2], keys[i + 1][1], keys[i + 1][2]
\tlocal h = t1 - t0
\tif h <= 0 then return v0 end
\tlocal m0, m1 = slope(i), slope(i + 1)
\tlocal u = (t - t0) / h
\tlocal u2, u3 = u * u, u * u * u
\treturn (2 * u3 - 3 * u2 + 1) * v0 + (u3 - 2 * u2 + u) * h * m0 + (-2 * u3 + 3 * u2) * v1 + (u3 - u2) * h * m1
end

function Clips.length(name: string): number
\tlocal clip = Clips.Data[name]
\treturn if clip then clip.length else 0
end

export type Out = {pitch: number, yaw: number, roll: number, bob: number, fwd: number}
function Clips.new(): Out return {pitch = 0, yaw = 0, roll = 0, bob = 0, fwd = 0} end

-- Writes the clip offsets of one part (role, side -1 / 1) at time t into out; all zero for an unknown clip, a missing track or t outside the clip.
-- "neck" uses its own track when the clip has one, otherwise the head track at NeckShare. bob comes from the root track for every role.
function Clips.sample(name: string, role: string, side: number, t: number, out: Out): Out
\tout.pitch, out.yaw, out.roll, out.bob, out.fwd = 0, 0, 0, 0, 0
\tlocal clip = Clips.Data[name]
\tif not clip or t ~= t then return out end
\tlocal tracks = clip.tracks :: any
\tif tracks.root and tracks.root.bob then out.bob = hermite(tracks.root.bob, t) end
\tlocal track, k = tracks[role], 1
\tif not track and role == "neck" then track, k = tracks.head, Clips.NeckShare end
\tif not track or role == "root" then return out end
\tlocal d = math.pi / 180 * k
\tif track.pitch then out.pitch = hermite(track.pitch, t) * d end
\tif track.yaw then out.yaw = hermite(track.yaw, t) * d end
\tif track.roll then out.roll = hermite(track.roll, t) * d * (if Clips.SideRoll[role] and side < 0 then -1 else 1) end
\tif track.fwd and role == "head" then out.fwd = hermite(track.fwd, t) end
\treturn out
end

return Clips''')
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    ns = load()
    bad = problems(ns)
    for p in bad:
        print("PROBLEM:", p)
    text = render(ns)
    if args.check:
        current = DEST.read_text(encoding="utf8") if DEST.exists() else ""
        if current != text:
            print("PROBLEM: %s is out of date; run python tools/blender/gen_dino_clips_luau.py" % DEST.relative_to(ROOT).as_posix())
            return 1
        if not bad:
            print("ok: LowPolyClips.luau matches dino_clips.py (%d clips)" % len(ns["CLIPS"]))
        return 1 if bad else 0
    if bad:
        return 1
    DEST.write_text(text, encoding="utf8", newline="\n")
    print("wrote", DEST.relative_to(ROOT).as_posix(), len(text), "bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
