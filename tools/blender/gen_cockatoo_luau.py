"""Generate assets/blender/creatures/CockatooAnimations.luau from tools/blender/cockatoo_anim.py (single source for the Blender actions and the Luau data).

Run: python tools/blender/gen_cockatoo_luau.py   (plain Python, no Blender needed; the joint table is read from build_cockatoo_hq.py by regex)
Blender frame (x right, y forward, z up) -> Roblox frame: (x, y, z) -> (x, z, -y).
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
ns = {}
exec((HERE / "cockatoo_anim.py").read_text(encoding="utf8"), ns)
ANIMS, PARTS, PARENT = ns["ANIMS"], ns["PARTS"], ns["PARENT"]

src = (HERE / "build_cockatoo_hq.py").read_text(encoding="utf8")
joints = {}
block = src[src.index("JOINTS = {"):src.index("}\n", src.index("JOINTS = {"))]
for m in re.finditer(r'"(\w+)": V\(\(([-\d.]+), ([-\d.]+), ([-\d.]+)\)\)', block):
    joints[m.group(1)] = tuple(float(m.group(i)) for i in (2, 3, 4))
assert set(joints) == set(PARTS), joints


def f(x):
    s = ("%.4f" % x).rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def vec(v):
    return "{%s}" % ", ".join(f(x) for x in v)


out = []
out.append('''--!strict
-- Cockatoo HQ test animations (BD-621, docs/evidence/2026-10-18-cockatoo-blender). GENERATED by tools/blender/gen_cockatoo_luau.py from
-- tools/blender/cockatoo_anim.py (the same keyframes author the Blender actions Idle / Walk / Jump). Pure data + functions: NOT required by any
-- game script and changes no behaviour. A Studio test model (anchored parts) uses it as: local rest = CockatooAnimations.capture(model); then every
-- frame CockatooAnimations.apply(model, rest, originCF, "Walk", os.clock()). In a game, CockatooAnimations.rig(model, originCF) builds Motor6Ds
-- and sample() gives their Transform values.
--
-- Model frame: studs, the Blender origin (ground, between the feet) is `originCF`; the creature faces -Z. Every part is rigid, its pivot is its joint.
-- Rotation keys are (pitch, roll, yaw) degrees in the model frame: pitch about +X (a hanging limb swings forward), roll about -Z, yaw about +Y.
-- Curves are cubic Hermite with auto-clamped tangents (like Blender auto-clamped Bezier): no overshoot, smooth loops.
local CockatooAnimations = {}

CockatooAnimations.Parts = {''' + ", ".join('"%s"' % p for p in PARTS) + '''}

-- parent part of every part (nil = the root part "Body")
CockatooAnimations.Parent = {''' + ", ".join('%s = "%s"' % (p, PARENT[p]) for p in PARTS if PARENT[p]) + '''}

-- joint position of every part in the model frame (studs): Roblox = (x, z, -y) of the Blender value
CockatooAnimations.Joints = {''')
for p in PARTS:
    x, y, z = joints[p]
    out.append('\t%s = Vector3.new(%s, %s, %s),' % (p, f(x), f(z), f(-y)))
out.append('}\n')
out.append('CockatooAnimations.Data = {')
for an, spec in ANIMS.items():
    out.append('\t%s = {length = %s, loop = %s, tracks = {' % (an, f(spec["length"]), "true" if spec["loop"] else "false"))
    for part in PARTS:
        tr = spec["tracks"].get(part)
        if not tr:
            continue
        pieces = []
        if "pos" in tr:
            pieces.append("pos = {%s}" % ", ".join("{%s, %s, %s, %s}" % (f(t), f(x), f(z), f(-y)) for (t, x, y, z) in tr["pos"]))
        if "rot" in tr:
            pieces.append("rot = {%s}" % ", ".join("{%s, %s, %s, %s}" % (f(t), f(p), f(r), f(w)) for (t, p, r, w) in tr["rot"]))
        out.append('\t\t%s = {%s},' % (part, ", ".join(pieces)))
    out.append('\t}},')
out.append('}\n')
out.append('''
-- value of one channel at time t from keys {{t, v}, ...} (sorted); loop = wrap around
local function hermite(keys: {{number}}, idx: number, t: number, length: number, loop: boolean): number
	local n = #keys
	local function key(i: number): (number, number)
		if loop then
			local wraps = 0
			while i < 1 do
				i += n - 1
				wraps -= 1
			end
			while i > n do
				i -= n - 1
				wraps += 1
			end
			return keys[i][1] + wraps * length, keys[i][idx]
		end
		return keys[math.clamp(i, 1, n)][1], keys[math.clamp(i, 1, n)][idx]
	end
	if n == 1 then
		return keys[1][idx]
	end
	if loop then
		t = t % length
	else
		t = math.clamp(t, 0, length)
	end
	local i = 1
	while i < n - 1 and keys[i + 1][1] <= t do
		i += 1
	end
	if not loop and t >= keys[n][1] then
		return keys[n][idx]
	end
	local t0, v0 = key(i)
	local t1, v1 = key(i + 1)
	local function slope(j: number): number
		local ta, va = key(j - 1)
		local tb, vb = key(j)
		local tc, vc = key(j + 1)
		if not loop and (j == 1 or j == n) then
			return 0
		end
		if (vb - va) * (vc - vb) <= 0 then
			return 0 -- local extremum: flat tangent (auto-clamped)
		end
		return (vc - va) / (tc - ta)
	end
	local m0, m1 = slope(i), slope(i + 1)
	local h = t1 - t0
	if h <= 0 then
		return v0
	end
	local u = (t - t0) / h
	local u2, u3 = u * u, u * u * u
	return (2 * u3 - 3 * u2 + 1) * v0 + (u3 - 2 * u2 + u) * h * m0 + (-2 * u3 + 3 * u2) * v1 + (u3 - u2) * h * m1
end

local function rotationOf(pitch: number, roll: number, yaw: number): CFrame
	return CFrame.fromAxisAngle(Vector3.yAxis, math.rad(yaw)) * CFrame.fromAxisAngle(Vector3.new(0, 0, -1), math.rad(roll)) * CFrame.fromAxisAngle(Vector3.xAxis, math.rad(pitch))
end

-- Motor6D.Transform of every animated part at time t (seconds) of animation `name` ("Idle" | "Walk" | "Jump")
function CockatooAnimations.sample(name: string, t: number): {[string]: CFrame}
	local anim = CockatooAnimations.Data[name]
	assert(anim, "unknown animation " .. tostring(name))
	local out: {[string]: CFrame} = {}
	for part, tr in anim.tracks do
		local pos = Vector3.zero
		if tr.pos then
			pos = Vector3.new(hermite(tr.pos, 2, t, anim.length, anim.loop), hermite(tr.pos, 3, t, anim.length, anim.loop), hermite(tr.pos, 4, t, anim.length, anim.loop))
		end
		local rot = CFrame.identity
		if tr.rot then
			rot = rotationOf(hermite(tr.rot, 2, t, anim.length, anim.loop), hermite(tr.rot, 3, t, anim.length, anim.loop), hermite(tr.rot, 4, t, anim.length, anim.loop))
		end
		out[part] = CFrame.new(pos) * rot
	end
	return out
end

-- Create (or reuse) a Motor6D per part under the parent's part. Call ONCE with the model assembled at rest (every MeshPart named like Parts,
-- unanchored except "Body" optional) and `originCF` = where the Blender origin (ground between the feet) is in the world.
function CockatooAnimations.rig(model: Model, originCF: CFrame): {[string]: Motor6D}
	local motors: {[string]: Motor6D} = {}
	for _, partName in CockatooAnimations.Parts do
		local parentName = (CockatooAnimations.Parent :: any)[partName]
		if parentName then
			local child = model:FindFirstChild(partName) :: BasePart
			local parent = model:FindFirstChild(parentName) :: BasePart
			assert(child and parent, "missing part " .. partName .. " / " .. parentName)
			local joint = originCF * CFrame.new(CockatooAnimations.Joints[partName])
			local m = child:FindFirstChild("Joint_" .. partName) :: Motor6D?
			if not m then
				m = Instance.new("Motor6D")
				m.Name = "Joint_" .. partName
				m.Parent = child
			end
			local mm = m :: Motor6D
			mm.Part0 = parent
			mm.Part1 = child
			mm.C0 = parent.CFrame:Inverse() * joint
			mm.C1 = child.CFrame:Inverse() * joint
			motors[partName] = mm
		end
	end
	return motors
end

-- Rest CFrames of every part (read once while the model is assembled at rest)
function CockatooAnimations.capture(model: Model): {[string]: CFrame}
	local rest: {[string]: CFrame} = {}
	for _, partName in CockatooAnimations.Parts do
		local part = model:FindFirstChild(partName) :: BasePart
		assert(part, "missing part " .. partName)
		rest[partName] = part.CFrame
	end
	return rest
end

-- World CFrame of every part for animation `name` at time t, by forward kinematics (no physics, no Motor6D): works for anchored parts in Edit mode.
-- D(part) = D(parent) * joint * Transform * joint^-1, posed = D(part) * rest
function CockatooAnimations.poseParts(rest: {[string]: CFrame}, originCF: CFrame, name: string, t: number): {[string]: CFrame}
	local pose = CockatooAnimations.sample(name, t)
	local displacement: {[string]: CFrame} = {}
	local posed: {[string]: CFrame} = {}
	for _, partName in CockatooAnimations.Parts do -- parents are listed before children
		local joint = originCF * CFrame.new(CockatooAnimations.Joints[partName])
		local parentName = (CockatooAnimations.Parent :: any)[partName]
		local parentD = if parentName then displacement[parentName] else CFrame.identity
		local d = parentD * joint * (pose[partName] or CFrame.identity) * joint:Inverse()
		displacement[partName] = d
		posed[partName] = d * rest[partName]
	end
	return posed
end

-- Move every part of `model` to the pose (set the parts Anchored for this use)
function CockatooAnimations.apply(model: Model, rest: {[string]: CFrame}, originCF: CFrame, name: string, t: number)
	for partName, cf in CockatooAnimations.poseParts(rest, originCF, name, t) do
		local part = model:FindFirstChild(partName) :: BasePart?
		if part then
			part.CFrame = cf
		end
	end
end

return CockatooAnimations
''')
dest = ROOT / "assets" / "blender" / "creatures" / "CockatooAnimations.luau"
dest.write_text("\n".join(out), encoding="utf8", newline="\n")
print("wrote", dest, dest.stat().st_size, "bytes")
