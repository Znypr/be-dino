"""Generate src/shared/WorldKitMeshAssets.luau from resources/worldkit-meshes/mesh-bindings.json.

Each entry is the uploaded kit MeshPart: its mesh asset and the size in studs
(Studio imported size * scale). Kit ids with no upload (null) are simply absent, so the
native fallback model stays in use for them. No hand-copied IDs.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BINDINGS = ROOT / 'resources/worldkit-meshes/mesh-bindings.json'
MANIFEST = ROOT / 'assets/blender/world/world-kit-manifest.json'
OUTPUT = ROOT / 'src/shared/WorldKitMeshAssets.luau'


def num(value):
    return f'{round(value, 4):g}'


def compile_bindings(data=None, kit_ids=None):
    data = data if data is not None else json.loads(BINDINGS.read_text())
    kit_ids = kit_ids if kit_ids is not None else [a['id'] for a in json.loads(MANIFEST.read_text())['assets']]
    meshes = data['meshes']
    unknown = set(meshes) - set(kit_ids)
    if unknown:
        raise ValueError(f'Bindings for unknown kit ids: {sorted(unknown)}')
    missing = set(data.get('missing', []))
    if missing & set(meshes):
        raise ValueError('An id is both bound and listed as missing')
    unlisted = set(kit_ids) - set(meshes) - missing
    if unlisted:
        raise ValueError(f'Kit ids neither bound nor listed missing: {sorted(unlisted)}')
    lines = []
    for key in kit_ids:
        entry = meshes.get(key)
        if entry is None:
            continue
        mesh_id = entry['meshId']
        if not re.fullmatch(r'rbxassetid://[1-9][0-9]*', mesh_id):
            raise ValueError(f'Invalid mesh ID for {key}')
        scale = entry['scale']
        if not 0 < scale < 1:
            raise ValueError(f'Invalid scale for {key}')
        size = [a * scale for a in entry['importedSize']]
        if any(abs(a - b) > .005 * b for a, b in zip(size, entry['targetSize'])):
            raise ValueError(f'Scaled size of {key} differs from its target size by more than 0.5%')
        lines.append(f'    {key} = {{meshId = "{mesh_id}", size = {{{", ".join(num(a) for a in size)}}}}},\n')
    return ('--!strict\n-- Generated by tools/bind_worldkit_meshes.py from resources/worldkit-meshes/mesh-bindings.json.\n'
            '-- size is in studs; ids missing here keep the native fallback model.\nreturn {\n' + ''.join(lines) + '}\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = compile_bindings()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            raise SystemExit('World kit mesh mapping is stale. Run python tools/bind_worldkit_meshes.py')
    else:
        OUTPUT.write_text(content, newline='\n')
    print('World kit mesh bindings verified' if args.check else 'World kit mesh bindings generated')
