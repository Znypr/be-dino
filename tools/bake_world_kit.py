"""Bake the BD-049/050 Blender OBJ exports into permission-free native Roblox models.

Reads assets/blender/world/world-kit-manifest.json and resources/models/world/*.obj
(written by tools/blender/build_world_kit.py) and writes:
- resources/worldkit/<id>.rbxmx  (two fitted WedgePart surfaces per triangle,
  packaged into ReplicatedStorage.WorldKit; same technique as bake_models.py)
- src/shared/WorldKitData.luau   (triangles, bounds, collider proxies per asset)
Run: python tools/bake_world_kit.py [--check]
"""
from pathlib import Path
import argparse, json, sys
import xml.etree.ElementTree as E
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "assets/blender/world/world-kit-manifest.json"
OUT = ROOT / "resources/worldkit"
DATA = ROOT / "src/shared/WorldKitData.luau"
NO_SHADOW = {"groundcover", "shrub", "food"}


def read_obj(path):
    colours, mat = {}, None
    for line in path.with_suffix(".mtl").read_text().splitlines():
        if line.startswith("newmtl "): mat = line.split()[1]
        elif line.startswith("Kd "): colours[mat] = [float(x) for x in line.split()[1:]]
    verts, faces, current = [], [], None
    for line in path.read_text().splitlines():
        if line.startswith("v "): verts.append([float(x) for x in line.split()[1:]])
        elif line.startswith("usemtl "): current = colours[line.split()[1]]
        elif line.startswith("f "): faces.append(([int(x) - 1 for x in line.split()[1:]], current))
    return verts, faces


def prop(props, kind, name, value):
    e = E.SubElement(props, kind, {"name": name}); e.text = str(value)


def bake(asset):
    verts, faces = read_obj(ROOT / asset["obj"])
    root = E.Element("roblox", {"version": "4"})
    model = E.SubElement(root, "Item", {"class": "Model", "referent": "model"})
    prop(E.SubElement(model, "Properties"), "string", "Name", asset["id"])
    count = 0
    for idx, colour in faces:
        a, b, c = [np.array(verts[i]) for i in idx]
        ab, ac, bc = b - a, c - a, c - b
        if ab @ ab > max(ac @ ac, bc @ bc): a, c = c, a
        elif ac @ ac > max(ab @ ab, bc @ bc): a, b = b, a
        ab, ac, bc = b - a, c - a, c - b
        right = np.cross(ac, ab); right /= np.linalg.norm(right)
        back = bc / np.linalg.norm(bc); up = np.cross(back, right)
        height = abs(ab @ up)
        for centre, r, z, length in (((a + b) / 2, right, back, abs(ab @ back)), ((a + c) / 2, -right, -back, abs(ac @ back))):
            if length < 1e-6: continue
            count += 1
            part = E.SubElement(model, "Item", {"class": "WedgePart", "referent": f"w{count}"})
            p = E.SubElement(part, "Properties"); prop(p, "string", "Name", f"Surface{count}")
            size = E.SubElement(p, "Vector3", {"name": "size"})
            for k, v in zip("XYZ", (.01, height, length)): E.SubElement(size, k).text = f"{v:.5f}"
            cf = E.SubElement(p, "CoordinateFrame", {"name": "CFrame"})
            for k, v in zip("XYZ", centre): E.SubElement(cf, k).text = f"{v:.5f}"
            m = np.column_stack((r, up, z))
            for i in range(3):
                for j in range(3): E.SubElement(cf, f"R{i}{j}").text = f"{m[i, j]:.6f}"
            rgb = [round(v * 255) for v in colour]
            prop(p, "Color3uint8", "Color3uint8", (255 << 24) | (rgb[0] << 16) | (rgb[1] << 8) | rgb[2])
            shadow = "false" if asset["kind"] in NO_SHADOW else "true"
            for k, v in (("Anchored", "true"), ("CanCollide", "false"), ("CanTouch", "false"), ("CanQuery", "false"), ("Massless", "true"), ("CastShadow", shadow)):
                prop(p, "bool", k, v)
            prop(p, "token", "Material", 272)
    E.indent(root)
    return E.tostring(root, encoding="utf-8", xml_declaration=True), count


def luau(manifest):
    lines = ["--!strict", "-- Generated by tools/bake_world_kit.py from assets/blender/world/world-kit-manifest.json.", "return {"]
    for a in manifest["assets"]:
        lo, hi = a["bounds"]
        size = [round(hi[i] - lo[i], 3) for i in range(3)]
        cols = ",".join("{%s}" % ",".join(str(round(x, 3)) for x in (*c["centre"], *c["size"], c["yaw"])) for c in a["colliders"])
        lines.append(f'    {a["id"]}={{kind="{a["kind"]}",family="{a["family"]}",size="{a["sizeClass"]}",triangles={a["triangles"]},'
                     f'extent={{{",".join(map(str, size))}}},colliders={{{cols}}}}},')
    lines.append("}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(); parser.add_argument("--check", action="store_true"); args = parser.parse_args()
    manifest = json.loads(MANIFEST.read_text())
    outputs = {DATA: luau(manifest).encode()}
    for a in manifest["assets"]:
        data, count = bake(a)
        outputs[OUT / f"{a['id']}.rbxmx"] = data
    stale = [p for p, d in outputs.items() if not p.exists() or p.read_bytes() != d]
    if args.check:
        if stale: sys.exit("Stale world kit outputs: " + ", ".join(p.name for p in stale))
        print(f"World kit outputs current ({len(outputs)} files)")
    else:
        OUT.mkdir(parents=True, exist_ok=True)
        for p, d in outputs.items(): p.write_bytes(d)
        print(f"Baked {len(manifest['assets'])} world kit models")
