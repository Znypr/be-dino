#!/usr/bin/env python3
"""Regenerate (or check) the counts block in docs/07-kanban.md.

The block lives between <!-- board-summary:begin --> and <!-- board-summary:end -->.
Counts only; the hand-ordered top-10 list stays outside the markers.

  python tools/board_summary.py          # rewrite the block
  python tools/board_summary.py --check  # exit 1 if the block is stale
"""
import re
import sys
from pathlib import Path

KANBAN = Path(__file__).resolve().parent.parent / "docs" / "07-kanban.md"
CRLF, LF = chr(13) + chr(10), chr(10)
BEGIN, END = "<!-- board-summary:begin -->", "<!-- board-summary:end -->"
# "Review / test" must be tried before the bare legacy "Review".
STATUSES = ["Backlog", "Ready", "In progress", "In review", "Review / test", "Review", "Blocked", "Done",
            "Superseded", "Parked", "Spike"]
PRIOS = ["P0", "P1", "P2", "P3"]
ROW = re.compile(r"^\| (BD-\d+) \| ([^|]*?) \| (P\d)\b")


def normalise(raw):
    s = raw.strip().lower()
    for name in STATUSES:
        if s.startswith(name.lower()):
            return "Review / test" if name == "Review" else name
    return "Other"


def count(text):
    seen, table = set(), {}
    for line in text.splitlines():
        m = ROW.match(line)
        if not m or m[1] in seen:
            continue
        seen.add(m[1])
        key = (normalise(m[2]), m[3])
        table[key] = table.get(key, 0) + 1
    return len(seen), table


def block(text):
    total, table = count(text)
    order = [s for s in STATUSES if s != "Review"] + ["Other"]
    out = [BEGIN, "",
           "**Board summary (generated by `tools/board_summary.py`, counts only):** %d tasks." % total, "",
           "| Status | " + " | ".join(PRIOS) + " | Total |", "|---|" + "---:|" * (len(PRIOS) + 1)]
    for st in order:
        cells = [table.get((st, p), 0) for p in PRIOS]
        if sum(cells):
            out.append("| %s | %s | %d |" % (st, " | ".join(map(str, cells)), sum(cells)))
    col = [sum(v for k, v in table.items() if k[1] == p) for p in PRIOS]
    out.append("| **Total** | %s | %d |" % (" | ".join(map(str, col)), total))
    out += ["", END]
    return LF.join(out)


def main():
    raw = KANBAN.read_bytes().decode("utf-8")
    eol = CRLF if CRLF in raw else LF
    text = raw.replace(CRLF, LF)
    if BEGIN not in text or END not in text:
        print("markers missing in %s" % KANBAN)
        return 1
    pre, rest = text.split(BEGIN, 1)
    _, post = rest.split(END, 1)
    new = pre + block(text) + post
    if "--check" in sys.argv:
        if new != text:
            print("docs/07-kanban.md board summary is stale: run python tools/board_summary.py")
            return 1
        print("board summary current")
        return 0
    KANBAN.write_bytes(new.replace(LF, eol).encode("utf-8"))
    print("board summary updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
