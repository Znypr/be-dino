"""Pure helpers for the sheet -> Hunyuan3D -> game dino route (BD-1304). No bpy, no numpy: imported by tools/hy_dino.py, by
tools/blender/hy_dino_blender.py inside Blender, and by tests/test_hy_dino.py.

- select_tips: spike tips from (strength, point, normal) candidates, strongest first, merged by distance, capped at a count
- species_config: a species config (cut planes, part labels, budgets) from measured anatomy and a body plan template
- panels_from_columns / figure_rows: find the sheet's figures from per-column / per-row foreground counts
"""
from __future__ import annotations

import math

PLANS = ("quadruped", "biped", "flyer")


def _dist(a, b):
    return math.sqrt(sum((x - y) ** 2 for x, y in zip(a, b)))


def select_tips(cands, merge, count=None, floor=0.0):
    """cands: [(strength, point(x,y,z), normal)], one side (x >= 0). Strongest first; a candidate closer than `merge` to a tip already
    taken is skipped; stops at `count` tips (None = all) and ignores strengths below `floor`. Returns [(point, normal)]."""
    tips = []
    for s, p, n in sorted(cands, key=lambda c: -c[0]):
        if s < floor:
            break
        if all(_dist(p, t) > merge for t, _ in tips):
            tips.append((p, n))
            if count is not None and len(tips) >= count:
                break
    return tips


def mirror_tips(tips, centre_x=0.05):
    """Add the -X twin of every tip that is not on the centre line."""
    out = list(tips)
    for (x, y, z), (nx, ny, nz) in tips:
        if x > centre_x:
            out.append(((-x, y, z), (-nx, ny, nz)))
    return out


def runs(mask, min_len=1, gap=0):
    """[(start, end)] of True runs in a list of bools; runs separated by at most `gap` False items are joined."""
    out = []
    i, n = 0, len(mask)
    while i < n:
        if mask[i]:
            j = i
            while j < n and mask[j]:
                j += 1
            if out and i - out[-1][1] <= gap:
                out[-1] = (out[-1][0], j)
            else:
                out.append((i, j))
            i = j
        else:
            i += 1
    return [(a, b) for a, b in out if b - a >= min_len]


def panels_from_columns(col_counts, want=4, min_width=20):
    """Figure x-ranges in the sheet's top row from per-column foreground counts. Joins tiny gaps (spikes, tails) until exactly
    `want` ranges remain when possible: the widest gaps are kept as separators."""
    mask = [c > 2 for c in col_counts]
    r = runs(mask, min_len=1)
    r = [x for x in r if x[1] - x[0] >= 3]
    while len(r) > want:
        gaps = [(r[i + 1][0] - r[i][1], i) for i in range(len(r) - 1)]
        _, i = min(gaps)
        r[i:i + 2] = [(r[i][0], r[i + 1][1])]
    return [x for x in r if x[1] - x[0] >= min_width]


def figure_rows(row_counts, min_gap=4):
    """(top, bottom) of the figure in one column band: the first vertical run of foreground rows, so a label pill under the figure
    (separated by at least `min_gap` empty rows) is not included."""
    r = runs([c > 1 for c in row_counts], min_len=3, gap=min_gap - 1)
    return r[0] if r else (0, len(row_counts))


def species_config(name, plan, a):
    """Species config source text for build stage 'parts' from anatomy `a` (tools/blender/hy_dino_blender.py --stage measure):
    a = {"size": [w, l, h], "y": [ymin, ymax], "legs": [[y0, y1], ...] front to back, "leg_top": z, "leg_inner": |x|,
         "head_y": y where the head starts, "tail_y": y where the tail starts, "wing": optional {"x": |x|, "z": [z0, z1]}}."""
    if plan not in PLANS:
        raise ValueError("plan must be one of %s" % (PLANS,))
    legs = a["legs"]
    lines = ["# %s (%s). Generated by tools/hy_dino.py config from the measured shape; edit freely." % (name, plan),
             "NAME = %r" % name]
    if plan == "quadruped":
        parts = ["Body", "Head", "Tail", "LegFL", "LegFR", "LegBL", "LegBR"]
        budget = {"Body": 1100, "Head": 380, "Tail": 220, "LegFL": 150, "LegFR": 150, "LegBL": 150, "LegBR": 150}
        front, back = legs[0], legs[-1]
        lines += ["PARTS = %r" % parts, "BUDGET = %r" % budget,
                  "HEAD_Y, TAIL_Y, LEG_Z, LEG_X = %.2f, %.2f, %.2f, %.2f" % (a["head_y"], a["tail_y"], a["leg_top"], a["leg_inner"]),
                  "FRONT = (%.2f, %.2f)" % (front[0] - 0.05, front[1] + 0.05),
                  "BACK = (%.2f, %.2f)" % (back[0] - 0.05, back[1] + 0.05),
                  "MID = %.2f" % ((front[0] + back[1]) / 2),
                  "",
                  "def label(c):",
                  "    if c.y > HEAD_Y and c.z > LEG_Z:",
                  "        return 'Head'",
                  "    if c.y < TAIL_Y and c.z > LEG_Z * 0.5:",
                  "        return 'Tail'",
                  "    if c.z < LEG_Z and abs(c.x) > LEG_X and (FRONT[0] < c.y < FRONT[1] or BACK[0] < c.y < BACK[1]):",
                  "        return 'Leg' + ('F' if c.y > MID else 'B') + ('L' if c.x < 0 else 'R')",
                  "    return 'Body'",
                  "",
                  "CUTS = [",
                  "    ((0, HEAD_Y, 0), (0, 1, 0), ((-9, -9, LEG_Z), (9, 9, 9))),",
                  "    ((0, TAIL_Y, 0), (0, 1, 0), None),",
                  "    ((0, 0, LEG_Z), (0, 0, 1), ((LEG_X - 0.05, FRONT[0], 0), (9, FRONT[1], LEG_Z + 0.05))),",
                  "    ((0, 0, LEG_Z), (0, 0, 1), ((LEG_X - 0.05, BACK[0], 0), (9, BACK[1], LEG_Z + 0.05))),",
                  "    ((LEG_X, 0, 0), (1, 0, 0), ((0, -9, 0), (9, 9, LEG_Z + 0.05))),",
                  "]"]
    else:
        parts = ["Body", "Head", "Tail", "LegL", "LegR"] + (["WingL", "WingR"] if plan == "flyer" else ["ArmL", "ArmR"])
        budget = {"Body": 520, "Head": 480, "Tail": 200, "LegL": 220, "LegR": 220, "ArmL": 80, "ArmR": 80, "WingL": 260, "WingR": 260}
        budget = {k: v for k, v in budget.items() if k in parts}
        leg = legs[0]
        w = a.get("wing") or {"x": a["leg_inner"] + 0.2, "z": [a["leg_top"] + 0.1, a["head_z"] - 0.05]}
        limb = "Wing" if plan == "flyer" else "Arm"
        lines += ["PARTS = %r" % parts, "BUDGET = %r" % budget,
                  "HEAD_Z, TAIL_Y, LEG_Z, LEG_X = %.2f, %.2f, %.2f, %.2f" % (a["head_z"], a["tail_y"], a["leg_top"], a["leg_inner"]),
                  "LEGS = (%.2f, %.2f)" % (leg[0] - 0.05, leg[1] + 0.05),
                  "LIMB_X, LIMB_Z = %.2f, (%.2f, %.2f)" % (w["x"], w["z"][0], w["z"][1]),
                  "",
                  "def label(c):",
                  "    if c.z > HEAD_Z:",
                  "        return 'Head'",
                  "    if c.y < TAIL_Y and c.z > LEG_Z * 0.6:",
                  "        return 'Tail'",
                  "    if abs(c.x) > LIMB_X and LIMB_Z[0] < c.z < LIMB_Z[1]:",
                  "        return %r + ('L' if c.x < 0 else 'R')" % limb,
                  "    if c.z < LEG_Z and abs(c.x) > LEG_X and LEGS[0] < c.y < LEGS[1]:",
                  "        return 'Leg' + ('L' if c.x < 0 else 'R')",
                  "    return 'Body'",
                  "",
                  "CUTS = [",
                  "    ((0, 0, HEAD_Z), (0, 0, 1), None),",
                  "    ((0, TAIL_Y, 0), (0, 1, 0), ((-9, -9, LEG_Z * 0.6), (9, 9, HEAD_Z))),",
                  "    ((LIMB_X, 0, 0), (1, 0, 0), ((0, -9, LIMB_Z[0]), (9, 9, LIMB_Z[1]))),",
                  "    ((0, 0, LEG_Z), (0, 0, 1), ((LEG_X - 0.05, LEGS[0], 0), (9, LEGS[1], LEG_Z + 0.05))),",
                  "    ((LEG_X, 0, 0), (1, 0, 0), ((0, LEGS[0], 0), (9, LEGS[1], LEG_Z + 0.05))),",
                  "]"]
    lines += ["", "# colours: project the sheet's side/front/back drawings (tools/hy_dino.py sheet wrote the crops)",
              "PROJECT = {'views': ['front', 'side', 'back']}",
              "# optional overrides (see docs/169 section 8): TOP = {...}, SPIKES = {...}, BUMP_COLOUR = '#RRGGBB', REGIONS = [...]",
              ""]
    return "\n".join(lines)
